#!/usr/bin/env python3
"""INT <-> DE string mapping report.
Inputs (made by Me1Tlk export): data/en (INT pkgs, EN text), data/de (DE pkgs, DE text), data/de-in-int (INT pkgs, tlk_DE text).
Outputs: data/mapping-report.json and docs/mapping-report.md"""
import glob, json, os, sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load(d):
    out = {}
    for p in glob.glob(os.path.join(ROOT, d, "*.json")):
        n = os.path.basename(p)
        if n.startswith("_"):
            continue
        out[n[:-5]] = {e["key"]: e["en"] for e in json.load(open(p, encoding="utf-8"))["entries"]}
    return out


en, de, dint = load("data/en"), load("data/de"), load("data/de-in-int")
r = {}
r["files"] = {"int": len(en), "de": len(de), "int_only": sorted(set(en) - set(de)), "de_only": sorted(set(de) - set(en))}

# string-level, only for packages present in both
tot = defaultdict(int)
per_file = {}
de_ids_without_en = {}
for stem in sorted(set(en) & set(de)):
    e, d = en[stem], de[stem]
    ek, dk = set(e), set(d)
    only_en, only_de = ek - dk, dk - ek
    tot["en_strings"] += len(ek)
    tot["de_strings"] += len(dk)
    tot["shared"] += len(ek & dk)
    tot["en_only"] += len(only_en)
    tot["de_only"] += len(only_de)
    if only_en or only_de:
        per_file[stem] = {"en_only": len(only_en), "de_only": len(only_de)}
    if only_de:
        de_ids_without_en[stem] = sorted(only_de)[:20]
r["strings_shared_packages"] = dict(tot)
r["files_with_id_mismatch"] = len(per_file)
r["id_mismatch_examples"] = dict(list(per_file.items())[:15])
r["de_ids_without_en_examples"] = dict(list(de_ids_without_en.items())[:10])

# is the tlk_DE text inside the INT packages the same as the DE packages' text?
same = diff = missing = 0
for stem in set(dint) & set(de):
    for k, t in dint[stem].items():
        if k in de[stem]:
            if de[stem][k] == t:
                same += 1
            else:
                diff += 1
        else:
            missing += 1
r["int_tlk_DE_vs_de_pkg"] = {"same_text": same, "different_text": diff, "id_not_in_de_pkg": missing}

# INT-only files: how much EN text sits in files with no DE twin
io = r["files"]["int_only"]
r["int_only_strings"] = sum(len(en[s]) for s in io)
r["int_only_with_tlk"] = sum(1 for s in io if en[s])
r["int_only_files_with_strings"] = {s: len(en[s]) for s in io if en[s]}

json.dump(r, open(os.path.join(ROOT, "data/mapping-report.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)

md = ["# INT <-> DE mapping report (generated by tools/mapping.py)", "",
      f"- INT packages exported: {r['files']['int']}; DE packages: {r['files']['de']} (both include Startup).",
      f"- Only in INT ({len(io)}): {', '.join(io[:6])} ...", f"- Only in DE: {r['files']['de_only']}",
      f"- INT-only packages that contain TLK strings: {r['int_only_with_tlk']} files, {r['int_only_strings']} strings.",
      f"- Packages in both: strings EN={tot['en_strings']}, DE={tot['de_strings']}, shared keys={tot['shared']}, EN-only={tot['en_only']}, DE-only={tot['de_only']}.",
      f"- Files with any id mismatch: {len(per_file)}.",
      f"- tlk_DE inside *_LOC_INT.pcc vs the DE package text: same={same}, different={diff}, id missing in DE pkg={missing}.", ""]
open(os.path.join(ROOT, "docs/mapping-report.md"), "w", encoding="utf-8").write("\n".join(md))
print("\n".join(md))
